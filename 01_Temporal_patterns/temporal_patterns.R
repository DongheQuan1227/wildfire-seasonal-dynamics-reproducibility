# Resolve paths relative to this script, so the code can be run from any
# working directory in RStudio or with Rscript.
get_script_dir <- function() {
  args <- commandArgs(trailingOnly = FALSE)
  file_arg <- grep("^--file=", args, value = TRUE)
  if (length(file_arg) > 0) {
    return(dirname(normalizePath(
      sub("^--file=", "", file_arg[1]),
      winslash = "/",
      mustWork = TRUE
    )))
  }
  
  frame_files <- vapply(
    sys.frames(),
    function(frame) {
      if (!is.null(frame$ofile)) as.character(frame$ofile) else NA_character_
    },
    character(1)
  )
  frame_files <- frame_files[!is.na(frame_files) & nzchar(frame_files)]
  if (length(frame_files) > 0) {
    return(dirname(normalizePath(
      tail(frame_files, 1),
      winslash = "/",
      mustWork = TRUE
    )))
  }
  
  if (
    requireNamespace("rstudioapi", quietly = TRUE) &&
    rstudioapi::isAvailable()
  ) {
    editor_path <- rstudioapi::getSourceEditorContext()$path
    if (nzchar(editor_path)) {
      return(dirname(normalizePath(
        editor_path,
        winslash = "/",
        mustWork = TRUE
      )))
    }
  }
  
  stop(
    "Cannot determine the script location. ",
    "Run the whole file with RStudio Source or Rscript."
  )
}

