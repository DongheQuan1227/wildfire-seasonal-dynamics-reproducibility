build_fc_ba_distribution <- function(group_fields) {
  fc_groups <- fire_events[, group_fields, drop = FALSE]
  fc <- aggregate(
    list(Count = rep(1, nrow(fire_events))),
    by = fc_groups,
    FUN = sum
  )
  
  ba_groups <- ba_events[, group_fields, drop = FALSE]
  ba <- aggregate(
    list(Area = ba_events$Burned_Area_km2),
    by = ba_groups,
    FUN = sum,
    na.rm = TRUE
  )
  
  complete_values <- lapply(group_fields, function(field) {
    if (field == "Year") return(2001:2025)
    if (field == "Month") return(1:12)
    if (field == "DOY") return(1:366)
    if (field == "Country") return(c("China", "North_Korea", "Russia"))
    sort(unique(c(fire_events[[field]], ba_events[[field]])))
  })
  names(complete_values) <- group_fields
  complete_grid <- do.call(
    expand.grid,
    c(
      complete_values,
      list(KEEP.OUT.ATTRS = FALSE, stringsAsFactors = FALSE)
    )
  )
  
  output <- merge(complete_grid, fc, by = group_fields, all.x = TRUE)
  output <- merge(output, ba, by = group_fields, all.x = TRUE)
  output$Count[is.na(output$Count)] <- 0
  output$Area[is.na(output$Area)] <- 0
  output
}

# ============================================================
# 1. Functions for Mann-Kendall-equivalent Kendall trend test
#    and Sen's slope
# ============================================================

sen_fit <- function(x, y) {
  ok <- complete.cases(x, y)
  x <- x[ok]
  y <- y[ok]
  
  if (length(x) < 2) {
    stop("At least two complete observations are required.")
  }
  
  pair_index <- combn(seq_along(x), 2)
  dx <- x[pair_index[2, ]] - x[pair_index[1, ]]
  dy <- y[pair_index[2, ]] - y[pair_index[1, ]]
  
  valid_pairs <- dx != 0
  slopes <- dy[valid_pairs] / dx[valid_pairs]
  
  slope <- median(slopes, na.rm = TRUE)
  intercept <- median(y - slope * x, na.rm = TRUE)
  
  list(
    slope = slope,
    intercept = intercept
  )
}

trend_test <- function(data, response, period_name) {
  x <- data$Year
  y <- data[[response]]
  ok <- complete.cases(x, y)
  x <- x[ok]
  y <- y[ok]
  
  mk <- cor.test(
    x,
    y,
    method = "kendall",
    exact = FALSE
  )
  
  sen <- sen_fit(x, y)
  
  data.frame(
    Period = period_name,
    Response = response,
    N = length(y),
    Kendall_tau = unname(mk$estimate),
    P_value = mk$p.value,
    Sen_slope = sen$slope,
    stringsAsFactors = FALSE
  )
}


fmt_num <- function(x, digits = 3) {
