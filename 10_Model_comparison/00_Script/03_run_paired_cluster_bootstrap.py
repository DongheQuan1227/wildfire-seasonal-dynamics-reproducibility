def read_aligned(validation_scheme: str) -> pd.DataFrame:
    path = ALIGNED_FILES[validation_scheme]
    header = pd.read_csv(path, nrows=0)
    required = aligned_use_columns()

    missing = sorted(set(required) - set(header.columns))

    if missing:
        raise ValueError(
            f"{validation_scheme} aligned OOF is missing columns:\n"
            + "\n".join(missing)
        )

    data = pd.read_csv(
        path,
        usecols=required,
        dtype={
            "GRID_UID": str,
            "Country": str,
            "Count_Response": str,
        },
    )

    if len(data) != EXPECTED_ROWS_PER_SCHEME:
        raise ValueError(
            f"{validation_scheme} has {len(data):,} rows; "
            f"expected {EXPECTED_ROWS_PER_SCHEME:,}."
        )

    if data["GRID_UID"].nunique() != EXPECTED_GRID_COUNT:
        raise ValueError(
            f"{validation_scheme} does not contain "
            f"{EXPECTED_GRID_COUNT:,} grids."
        )

    if data.isna().any().any():
        missing_columns = (
            data.columns[data.isna().any()].tolist()
        )
        raise ValueError(
            f"{validation_scheme} has missing required values in: "
            + ", ".join(missing_columns)
        )

    return data


def build_grid_metadata(
    temporal_data: pd.DataFrame,
) -> pd.DataFrame:
    mapping = temporal_data[
        ["GRID_UID", "Country", "Spatial_Block"]
    ].drop_duplicates()

    duplicated = mapping.duplicated(
        "GRID_UID",
        keep=False,
    )

    if duplicated.any():
        mapping.loc[duplicated].to_csv(
            OUTPUT_ROOT / "ERROR_Grid_Metadata_Duplicates.csv",
            index=False,
            encoding="utf-8-sig",
        )
        raise ValueError(
            "GRID_UID does not have a unique Country/Spatial_Block mapping."
        )

    mapping["Spatial_Block"] = (
        mapping["Spatial_Block"].astype(int)
    )

    mapping = mapping.sort_values(
        "GRID_UID"
    ).reset_index(drop=True)

    if len(mapping) != EXPECTED_GRID_COUNT:
        raise ValueError(
            "Grid metadata does not contain the locked 4,982 grids."
        )

    mapping["Bootstrap_Stratum"] = (
        mapping["Country"].astype(str)
        + "__Block_"
        + mapping["Spatial_Block"].astype(str)
    )
    mapping["Grid_Index"] = np.arange(
        len(mapping),
        dtype=np.int32,
    )

    return mapping


def build_stratified_bootstrap_counts(
    grid_metadata: pd.DataFrame,
) -> Tuple[np.ndarray, pd.DataFrame, pd.DataFrame]:
    rng = np.random.default_rng(
        BOOTSTRAP_RANDOM_SEED
    )

    counts = np.zeros(
        (
            BOOTSTRAP_REPLICATES,
            len(grid_metadata),
        ),
        dtype=np.int16,
    )

    stratum_rows: List[Dict[str, object]] = []

    for stratum, group in grid_metadata.groupby(
        "Bootstrap_Stratum",
        sort=True,
    ):
        indices = group[
            "Grid_Index"
        ].to_numpy(dtype=np.int32)

        stratum_n = len(indices)

        draws = rng.multinomial(
            n=stratum_n,
            pvals=np.full(
                stratum_n,
                1.0 / stratum_n,
                dtype=np.float64,
            ),
            size=BOOTSTRAP_REPLICATES,
        )

        if draws.max() > np.iinfo(np.int16).max:
            raise OverflowError(
                "Bootstrap multiplicity exceeded int16 capacity."
            )

        counts[:, indices] = draws.astype(
            np.int16,
            copy=False,
        )

        replicate_totals = counts[
            :, indices
        ].sum(axis=1)

        stratum_rows.append(
            {
                "Bootstrap_Stratum": stratum,
                "Country": str(group["Country"].iloc[0]),
                "Spatial_Block": int(
                    group["Spatial_Block"].iloc[0]
                ),
                "Grid_Count": int(stratum_n),
                "Replicate_Min_Selected_Grid_Draws": int(
                    replicate_totals.min()
                ),
                "Replicate_Max_Selected_Grid_Draws": int(
                    replicate_totals.max()
                ),
                "Expected_Draws_Per_Replicate": int(
                    stratum_n
                ),
                "All_Replicates_Preserve_Stratum_Size": bool(
                    np.all(replicate_totals == stratum_n)
                ),
            }
        )

    replicate_total = counts.sum(axis=1)

    replicate_qa = pd.DataFrame(
        {
            "Bootstrap_Replicate": np.arange(
                1,
                BOOTSTRAP_REPLICATES + 1,
                dtype=np.int32,
            ),
            "Total_Grid_Draws": replicate_total.astype(
                np.int32
            ),
            "Unique_Grid_Count_Selected": np.count_nonzero(
                counts,
                axis=1,
            ).astype(np.int32),
            "Maximum_Grid_Multiplicity": counts.max(
                axis=1
            ).astype(np.int32),
        }
    )

    if not np.all(
        replicate_total == EXPECTED_GRID_COUNT
    ):
        raise ValueError(
            "Bootstrap replicates do not preserve total grid draws."
        )

    stratum_qa = pd.DataFrame(stratum_rows)

    if not stratum_qa[
        "All_Replicates_Preserve_Stratum_Size"
    ].all():
        raise ValueError(
            "One or more Country × Spatial_Block strata "
            "were not preserved."
        )

    return counts, stratum_qa, replicate_qa


