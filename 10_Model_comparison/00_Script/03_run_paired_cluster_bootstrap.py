def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()

    with path.open("rb") as file:
        while True:
            chunk = file.read(HASH_CHUNK_SIZE)

            if not chunk:
                break

            digest.update(chunk)

    return digest.hexdigest()


def sha256_array(array: np.ndarray) -> str:
    contiguous = np.ascontiguousarray(array)
    return hashlib.sha256(contiguous.tobytes()).hexdigest()


def read_json(path: Path) -> Dict[str, object]:
    with path.open("r", encoding="utf-8") as file:
        return json.load(file)


def write_json(path: Path, value: object) -> None:
    with path.open("w", encoding="utf-8") as file:
        json.dump(
            value,
            file,
            ensure_ascii=False,
            indent=2,
        )


def safe_divide(
    numerator: np.ndarray,
    denominator: np.ndarray,
) -> np.ndarray:
    result = np.full(
        np.broadcast_shapes(
            np.shape(numerator),
            np.shape(denominator),
        ),
        np.nan,
        dtype=np.float64,
    )

    np.divide(
        numerator,
        denominator,
        out=result,
        where=np.asarray(denominator) > 0,
    )

    return result


def safe_scalar_ratio(
    numerator: float,
    denominator: float,
) -> float:
    if not np.isfinite(denominator) or abs(denominator) <= 0:
        return np.nan

    return float(numerator / denominator)


def percentile_interval(
    values: np.ndarray,
) -> Tuple[float, float]:
    finite = np.asarray(values, dtype=np.float64)
    finite = finite[np.isfinite(finite)]

    if len(finite) == 0:
        return np.nan, np.nan

    alpha = 1.0 - CI_LEVEL

    return (
        float(np.quantile(finite, alpha / 2.0)),
        float(np.quantile(finite, 1.0 - alpha / 2.0)),
    )


def stable_conclusion(
    difference_ci_low: float,
    difference_ci_high: float,
) -> str:
    if (
        np.isfinite(difference_ci_high)
        and difference_ci_high < 0
    ):
        return "Candidate_stably_better"

    if (
        np.isfinite(difference_ci_low)
        and difference_ci_low > 0
    ):
        return "Reference_stably_better"

    return "No_stable_difference"


