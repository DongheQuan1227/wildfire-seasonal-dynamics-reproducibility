def verify_locked_inputs() -> pd.DataFrame:
    rows: List[Dict[str, object]] = []

    step01_method = read_json(STEP01_METHOD_FILE)
    step02_method = read_json(STEP02_METHOD_FILE)

    step01_version = str(
        step01_method.get("Code_Version", "")
    )
    step02_version = str(
        step02_method.get("Code_Version", "")
    )

    rows.append(
        {
            "Check": "Step01_Code_Version",
            "Observed": step01_version,
            "Expected": EXPECTED_STEP01_VERSION,
            "Passed": step01_version == EXPECTED_STEP01_VERSION,
        }
    )
    rows.append(
        {
            "Check": "Step02_Code_Version",
            "Observed": step02_version,
            "Expected": EXPECTED_STEP02_VERSION,
            "Passed": step02_version == EXPECTED_STEP02_VERSION,
        }
    )

    step01_manifest = pd.read_csv(STEP01_MANIFEST_FILE)

    for validation_scheme, path in ALIGNED_FILES.items():
        actual_hash = sha256_file(path)

        manifest_row = step01_manifest.loc[
            step01_manifest[
                "Validation_Scheme"
            ].astype(str) == validation_scheme
        ]

        manifest_hash = (
            str(manifest_row.iloc[0]["SHA256"])
            if len(manifest_row) == 1
            else ""
        )

        rows.append(
            {
                "Check": (
                    f"{validation_scheme}_Aligned_SHA256_"
                    "Matches_Step01_Manifest"
                ),
                "Observed": actual_hash,
                "Expected": manifest_hash,
                "Passed": actual_hash == manifest_hash,
            }
        )

    step02_manifest = pd.read_csv(STEP02_MANIFEST_FILE)

    for filename, path in [
        (
            "02_Overall_Unified_Prediction_Metrics.csv",
            STEP02_OVERALL_FILE,
        ),
        (
            "03_Fold_Level_Unified_Prediction_Metrics.csv",
            STEP02_FOLD_FILE,
        ),
    ]:
        manifest_row = step02_manifest.loc[
            step02_manifest["File"].astype(str) == filename
        ]

        expected_hash = (
            str(manifest_row.iloc[0]["SHA256"])
            if len(manifest_row) == 1
            else ""
        )
        actual_hash = sha256_file(path)

        rows.append(
            {
                "Check": f"{filename}_SHA256",
                "Observed": actual_hash,
                "Expected": expected_hash,
                "Passed": actual_hash == expected_hash,
            }
        )

    result = pd.DataFrame(rows)

    if not result["Passed"].all():
        result.to_csv(
            OUTPUT_ROOT / "ERROR_Input_Integrity_Audit.csv",
            index=False,
            encoding="utf-8-sig",
        )
        raise ValueError(
            "Locked Step 01 or Step 02 input integrity check failed."
        )

    return result


