def aggregate_by_grid(
    grid_index: np.ndarray,
    values: np.ndarray,
    grid_count: int,
) -> np.ndarray:
    return np.bincount(
        grid_index,
        weights=np.asarray(values, dtype=np.float64),
        minlength=grid_count,
    ).astype(np.float64, copy=False)


def build_group_statistics(
    group: pd.DataFrame,
    grid_metadata: pd.DataFrame,
) -> Tuple[
    np.ndarray,
    Dict[str, Dict[str, np.ndarray]],
    Dict[str, Dict[str, float]],
]:
    grid_lookup = pd.Series(
        grid_metadata[
            "Grid_Index"
        ].to_numpy(dtype=np.int32),
        index=grid_metadata["GRID_UID"].astype(str),
    )

    mapped = group["GRID_UID"].astype(str).map(
        grid_lookup
    )

    if mapped.isna().any():
        raise ValueError(
            "A group contains GRID_UID values outside the locked universe."
        )

    grid_index = mapped.to_numpy(dtype=np.int32)
    grid_count = len(grid_metadata)

    observed_count = group[
        "Observed_Count"
    ].to_numpy(dtype=np.float64)
    observed_rate = group[
        "Observed_Rate"
    ].to_numpy(dtype=np.float64)
    positive = observed_count > 0

    n_by_grid = aggregate_by_grid(
        grid_index,
        np.ones(len(group), dtype=np.float64),
        grid_count,
    )
    positive_n_by_grid = aggregate_by_grid(
        grid_index,
        positive.astype(np.float64),
        grid_count,
    )

    if np.count_nonzero(n_by_grid) != EXPECTED_GRID_COUNT:
        raise ValueError(
            "A season-response group does not contain all 4,982 grids."
        )

    model_statistics: Dict[
        str,
        Dict[str, np.ndarray],
    ] = {}
    point_metrics: Dict[
        str,
        Dict[str, float],
    ] = {}

    for model in MODELS:
        predicted_count = group[
            f"{model}_Predicted_Count"
        ].to_numpy(dtype=np.float64)
        predicted_rate = group[
            f"{model}_Predicted_Rate"
        ].to_numpy(dtype=np.float64)
        probability = group[
            f"{model}_Predicted_Positive_Probability"
        ].to_numpy(dtype=np.float64)
        conditional_count = group[
            (
                f"{model}_Predicted_"
                "Conditional_Positive_Count"
            )
        ].to_numpy(dtype=np.float64)
        conditional_rate = group[
            (
                f"{model}_Predicted_"
                "Conditional_Positive_Rate"
            )
        ].to_numpy(dtype=np.float64)

        count_error = predicted_count - observed_count
        rate_error = predicted_rate - observed_rate
        occurrence_error = (
            probability - positive.astype(np.float64)
        )

        conditional_count_error = (
            conditional_count - observed_count
        )
        conditional_rate_error = (
            conditional_rate - observed_rate
        )

        statistics = {
            "Rate_SSE": aggregate_by_grid(
                grid_index,
                np.square(rate_error),
                grid_count,
            ),
            "Rate_SAE": aggregate_by_grid(
                grid_index,
                np.abs(rate_error),
                grid_count,
            ),
            "Rate_Error_Sum": aggregate_by_grid(
                grid_index,
                rate_error,
                grid_count,
            ),
            "Count_SSE": aggregate_by_grid(
                grid_index,
                np.square(count_error),
                grid_count,
            ),
            "Count_SAE": aggregate_by_grid(
                grid_index,
                np.abs(count_error),
                grid_count,
            ),
            "Count_Error_Sum": aggregate_by_grid(
                grid_index,
                count_error,
                grid_count,
            ),
            "Occurrence_Brier_Sum": aggregate_by_grid(
                grid_index,
                np.square(occurrence_error),
                grid_count,
            ),
            "Occurrence_Error_Sum": aggregate_by_grid(
                grid_index,
                occurrence_error,
                grid_count,
            ),
            "Positive_Conditional_Rate_SSE": aggregate_by_grid(
                grid_index,
                np.where(
                    positive,
                    np.square(conditional_rate_error),
                    0.0,
                ),
                grid_count,
            ),
            "Positive_Conditional_Rate_SAE": aggregate_by_grid(
                grid_index,
                np.where(
                    positive,
                    np.abs(conditional_rate_error),
                    0.0,
                ),
                grid_count,
            ),
            "Positive_Conditional_Count_SSE": aggregate_by_grid(
                grid_index,
                np.where(
                    positive,
                    np.square(conditional_count_error),
                    0.0,
                ),
                grid_count,
            ),
            "Positive_Conditional_Count_SAE": aggregate_by_grid(
                grid_index,
                np.where(
                    positive,
                    np.abs(conditional_count_error),
                    0.0,
                ),
                grid_count,
            ),
        }

        model_statistics[model] = statistics

        n_total = float(n_by_grid.sum())
        positive_total = float(
            positive_n_by_grid.sum()
        )

        point_metrics[model] = {
            "Rate_RMSE": float(
                np.sqrt(
                    statistics["Rate_SSE"].sum()
                    / n_total
                )
            ),
            "Rate_MAE": float(
                statistics["Rate_SAE"].sum()
                / n_total
            ),
            "Count_RMSE": float(
                np.sqrt(
                    statistics["Count_SSE"].sum()
                    / n_total
                )
            ),
            "Count_MAE": float(
                statistics["Count_SAE"].sum()
                / n_total
            ),
            "Occurrence_Brier_Score": float(
                statistics[
                    "Occurrence_Brier_Sum"
                ].sum()
                / n_total
            ),
            "Positive_Conditional_Rate_RMSE": float(
                np.sqrt(
                    statistics[
                        "Positive_Conditional_Rate_SSE"
                    ].sum()
                    / positive_total
                )
            ),
            "Positive_Conditional_Rate_MAE": float(
                statistics[
                    "Positive_Conditional_Rate_SAE"
                ].sum()
                / positive_total
            ),
            "Positive_Conditional_Count_RMSE": float(
                np.sqrt(
                    statistics[
                        "Positive_Conditional_Count_SSE"
                    ].sum()
                    / positive_total
                )
            ),
            "Positive_Conditional_Count_MAE": float(
                statistics[
                    "Positive_Conditional_Count_SAE"
                ].sum()
                / positive_total
            ),
            "Rate_Absolute_Mean_Bias": float(
                abs(
                    statistics["Rate_Error_Sum"].sum()
                    / n_total
                )
            ),
            "Count_Absolute_Mean_Bias": float(
                abs(
                    statistics["Count_Error_Sum"].sum()
                    / n_total
                )
            ),
            "Occurrence_Absolute_Mean_Bias": float(
                abs(
                    statistics[
                        "Occurrence_Error_Sum"
                    ].sum()
                    / n_total
                )
            ),
        }

    return (
        np.column_stack(
            [
                n_by_grid,
                positive_n_by_grid,
            ]
        ),
        model_statistics,
        point_metrics,
    )


def calculate_bootstrap_model_metrics(
    bootstrap_counts_float: np.ndarray,
    denominators_by_grid: np.ndarray,
    model_statistics: Mapping[
        str,
        Mapping[str, np.ndarray],
    ],
) -> Dict[str, Dict[str, np.ndarray]]:
    n_by_grid = denominators_by_grid[:, 0]
    positive_n_by_grid = denominators_by_grid[:, 1]

    row_n = (
        bootstrap_counts_float @ n_by_grid
    )
    positive_n = (
        bootstrap_counts_float @ positive_n_by_grid
    )

    if np.any(row_n <= 0):
        raise ValueError(
            "A bootstrap replicate has no observations."
        )

    if np.any(positive_n <= 0):
        raise ValueError(
            "A bootstrap replicate has no positive observations."
        )

    output: Dict[
        str,
        Dict[str, np.ndarray],
    ] = {}

    for model in MODELS:
        statistics = model_statistics[model]

        names = list(statistics)
        statistic_matrix = np.column_stack(
            [statistics[name] for name in names]
        )

        totals = (
            bootstrap_counts_float @ statistic_matrix
        )

        total_by_name = {
            name: totals[:, index]
            for index, name in enumerate(names)
        }

        output[model] = {
            "Rate_RMSE": np.sqrt(
                safe_divide(
                    total_by_name["Rate_SSE"],
                    row_n,
                )
            ),
            "Rate_MAE": safe_divide(
                total_by_name["Rate_SAE"],
                row_n,
            ),
            "Count_RMSE": np.sqrt(
                safe_divide(
                    total_by_name["Count_SSE"],
                    row_n,
                )
            ),
            "Count_MAE": safe_divide(
                total_by_name["Count_SAE"],
                row_n,
            ),
            "Occurrence_Brier_Score": safe_divide(
                total_by_name[
                    "Occurrence_Brier_Sum"
                ],
                row_n,
            ),
            "Positive_Conditional_Rate_RMSE": np.sqrt(
                safe_divide(
                    total_by_name[
                        "Positive_Conditional_Rate_SSE"
                    ],
                    positive_n,
                )
            ),
            "Positive_Conditional_Rate_MAE": safe_divide(
                total_by_name[
                    "Positive_Conditional_Rate_SAE"
                ],
                positive_n,
            ),
            "Positive_Conditional_Count_RMSE": np.sqrt(
                safe_divide(
                    total_by_name[
                        "Positive_Conditional_Count_SSE"
                    ],
                    positive_n,
                )
            ),
            "Positive_Conditional_Count_MAE": safe_divide(
                total_by_name[
                    "Positive_Conditional_Count_SAE"
                ],
                positive_n,
            ),
            "Rate_Absolute_Mean_Bias": np.abs(
                safe_divide(
                    total_by_name["Rate_Error_Sum"],
                    row_n,
                )
            ),
            "Count_Absolute_Mean_Bias": np.abs(
                safe_divide(
                    total_by_name["Count_Error_Sum"],
                    row_n,
                )
            ),
            "Occurrence_Absolute_Mean_Bias": np.abs(
                safe_divide(
                    total_by_name[
                        "Occurrence_Error_Sum"
                    ],
                    row_n,
                )
            ),
        }

    return output


