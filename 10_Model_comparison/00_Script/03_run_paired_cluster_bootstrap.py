def expected_step02_metric(
    step02_row: pd.Series,
    metric: str,
) -> float:
    if metric == "Rate_Absolute_Mean_Bias":
        return float(abs(step02_row["Rate_Mean_Bias"]))

    if metric == "Count_Absolute_Mean_Bias":
        return float(abs(step02_row["Count_Mean_Bias"]))

    if metric == "Occurrence_Absolute_Mean_Bias":
        return float(
            abs(step02_row["Occurrence_Mean_Bias"])
        )

    return float(step02_row[metric])


def build_descriptive_nonadditive_differences(
    step02_overall: pd.DataFrame,
) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []

    for (
        validation_scheme,
        season,
        response,
    ), group in step02_overall.groupby(
        [
            "Validation_Scheme",
            "Season",
            "Count_Response",
        ],
        sort=True,
    ):
        indexed = group.set_index("Model")

        for (
            pair_name,
            candidate,
            reference,
        ) in MODEL_PAIRS:
            for (
                metric,
                direction,
            ) in NONADDITIVE_DESCRIPTIVE_METRICS.items():
                candidate_value = float(
                    indexed.loc[candidate, metric]
                )
                reference_value = float(
                    indexed.loc[reference, metric]
                )
                difference = (
                    candidate_value - reference_value
                )

                candidate_better = (
                    difference > 0
                    if direction == "Higher"
                    else difference < 0
                )

                rows.append(
                    {
                        "Validation_Scheme": validation_scheme,
                        "Season": int(season),
                        "Season_Label": SEASONS[int(season)],
                        "Count_Response": response,
                        "Model_Pair": pair_name,
                        "Candidate_Model": candidate,
                        "Reference_Model": reference,
                        "Metric": metric,
                        "Preferred_Direction": direction,
                        "Candidate_Value": candidate_value,
                        "Reference_Value": reference_value,
                        "Candidate_Minus_Reference": difference,
                        "Candidate_Better_Descriptively": bool(
                            candidate_better
                        ),
                        "Bootstrap_CI_Available": False,
                        "Reason_No_Bootstrap_CI": (
                            "This metric is rank-, threshold-, or "
                            "calibration-structure dependent and is "
                            "retained as a locked Step-02 descriptive "
                            "difference rather than mixed with the "
                            "exact sufficient-statistic bootstrap."
                        ),
                    }
                )

    return pd.DataFrame(rows)


def build_fold_win_counts(
    step02_fold: pd.DataFrame,
) -> pd.DataFrame:
    data = step02_fold.copy()

    data["Rate_Absolute_Mean_Bias"] = (
        data["Rate_Mean_Bias"].abs()
    )
    data["Count_Absolute_Mean_Bias"] = (
        data["Count_Mean_Bias"].abs()
    )
    data["Occurrence_Absolute_Mean_Bias"] = (
        data["Occurrence_Mean_Bias"].abs()
    )

    rows: List[Dict[str, object]] = []

    for (
        validation_scheme,
        season,
        response,
    ), group in data.groupby(
        [
            "Validation_Scheme",
            "Season",
            "Count_Response",
        ],
        sort=True,
    ):
        for (
            pair_name,
            candidate,
            reference,
        ) in MODEL_PAIRS:
            candidate_rows = (
                group.loc[group["Model"] == candidate]
                .set_index("Validation_Fold")
            )
            reference_rows = (
                group.loc[group["Model"] == reference]
                .set_index("Validation_Fold")
            )

            common_folds = sorted(
                set(candidate_rows.index)
                & set(reference_rows.index)
            )

            for metric in BOOTSTRAP_METRICS:
                candidate_values = candidate_rows.loc[
                    common_folds,
                    metric,
                ].to_numpy(dtype=np.float64)
                reference_values = reference_rows.loc[
                    common_folds,
                    metric,
                ].to_numpy(dtype=np.float64)

                valid = (
                    np.isfinite(candidate_values)
                    & np.isfinite(reference_values)
                )

                difference = (
                    candidate_values[valid]
                    - reference_values[valid]
                )

                tolerance = 1e-15

                rows.append(
                    {
                        "Validation_Scheme": validation_scheme,
                        "Season": int(season),
                        "Season_Label": SEASONS[int(season)],
                        "Count_Response": response,
                        "Model_Pair": pair_name,
                        "Candidate_Model": candidate,
                        "Reference_Model": reference,
                        "Metric": metric,
                        "Available_Fold_or_Block_N": int(
                            valid.sum()
                        ),
                        "Candidate_Better_N": int(
                            np.sum(difference < -tolerance)
                        ),
                        "Reference_Better_N": int(
                            np.sum(difference > tolerance)
                        ),
                        "Tie_N": int(
                            np.sum(
                                np.abs(difference) <= tolerance
                            )
                        ),
                        "Mean_Candidate_Minus_Reference": (
                            float(np.mean(difference))
                            if len(difference)
                            else np.nan
                        ),
                    }
                )

    return pd.DataFrame(rows)


